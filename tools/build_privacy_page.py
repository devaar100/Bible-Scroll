#!/usr/bin/env python3
"""
Builds the static privacy policy pages from the app's own strings, so the website and S8 Legal → Privacy can't
drift apart:

    python3 tools/build_privacy_page.py          # writes web/privacy/index.html and web/privacy/es/index.html
    python3 tools/build_privacy_page.py --check  # exits 1 if the committed pages are out of date

Sources: app/src/main/res/values{,-es}/strings.xml (privacy_* strings), PRIVACY_UPDATED in
data/legal/LegalData.kt, and supportEmail in app/build.gradle.kts (S7: the one place the address is defined).
Standard library only. Hosting: see web/README.md (a separate Firebase Hosting site; the content publish can't
touch it).
"""
from __future__ import annotations

import datetime
import html
import re
import sys
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "app/src/main/res"
LEGAL_DATA = ROOT / "app/src/main/java/aarnav100/developer/biblescroll/data/legal/LegalData.kt"
GRADLE = ROOT / "app/build.gradle.kts"
OUT = ROOT / "web/privacy"

#: Page order. ("h2", key) is a section heading; ("p", key) a paragraph.
LAYOUT = [
    ("p", "privacy_intro"),
    ("h2", "privacy_on_phone_title"), ("p", "privacy_on_phone"),
    ("h2", "privacy_leaves_title"),
    ("p", "privacy_leaves_content"), ("p", "privacy_leaves_vote"), ("p", "privacy_leaves_email"), ("p", "privacy_leaves_links"),
    ("h2", "privacy_android_title"), ("p", "privacy_android_backup"), ("p", "privacy_android_crashes"),
    ("h2", "privacy_sharing_title"), ("p", "privacy_sharing"),
    ("h2", "privacy_security_title"), ("p", "privacy_security"),
    ("h2", "privacy_retention_title"), ("p", "privacy_retention"),
    ("h2", "privacy_delete_title"), ("p", "privacy_delete"),
    ("h2", "privacy_rights_title"), ("p", "privacy_rights"), ("p", "privacy_legal_basis"),
    ("h2", "privacy_children_title"), ("p", "privacy_children"),
    ("h2", "privacy_contact_title"), ("p", "privacy_who"), ("p", "privacy_contact"),
    ("p", "privacy_changes"),
]
MONTHS = {
    "en": ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
    "es": ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"],
}


def android_unescape(text: str) -> str:
    """Android string escapes -> plain text (\\' \\" \\n \\@ \\?); XML entities are already decoded by the parser."""
    return re.sub(r"\\(.)", lambda m: "\n" if m.group(1) == "n" else m.group(1), text).strip()


def strings(lang: str) -> dict[str, str]:
    folder = "values" if lang == "en" else f"values-{lang}"
    root = ET.parse(RES / folder / "strings.xml").getroot()
    return {e.get("name"): android_unescape("".join(e.itertext())) for e in root.findall("string")}


def updated() -> datetime.date:
    m = re.search(r"PRIVACY_UPDATED: LocalDate = LocalDate\.of\((\d+), (\d+), (\d+)\)", LEGAL_DATA.read_text())
    if not m:
        sys.exit(f"PRIVACY_UPDATED not found in {LEGAL_DATA}")
    return datetime.date(*map(int, m.groups()))


def support_email() -> str:
    m = re.search(r'val supportEmail = "([^"]*)"', GRADLE.read_text())
    if not m:
        sys.exit(f"supportEmail not found in {GRADLE}")
    return m.group(1)


def developer_name() -> str:
    m = re.search(r'val developerName = "([^"]*)"', GRADLE.read_text())
    if not m:
        sys.exit(f"developerName not found in {GRADLE}")
    return m.group(1)


def fill(template: str, *args: str) -> str:
    """Android positional args (%1$s, %2$d)."""
    return re.sub(r"%(\d+)\$[sd]", lambda m: args[int(m.group(1)) - 1], template)


def page(lang: str) -> str:
    s, en = strings(lang), strings("en")
    get = lambda key: s.get(key) or en[key]  # English fallback per string, like the app
    date = updated()
    date_text = f"{date.day} {MONTHS[lang][date.month - 1]} {date.year}" if lang == "en" else f"{date.day} de {MONTHS[lang][date.month - 1]} de {date.year}"
    email = support_email()
    body = []
    for tag, key in LAYOUT:
        text = get(key)
        if key == "privacy_contact":
            label = html.escape(fill(text, "\x00"))
            link = f'<a href="mailto:{html.escape(email, quote=True)}">{html.escape(email)}</a>'
            body.append(f"<p>{label.replace(chr(0), link)}</p>")
        elif key == "privacy_who":
            body.append(f"<p>{html.escape(fill(text, developer_name()))}</p>")
        else:
            body.append(f"<{tag}>{html.escape(text)}</{tag}>")
    other = ('<a href="es/" hreflang="es">Español</a>' if lang == "en" else '<a href="../" hreflang="en">English</a>')
    return f"""<!doctype html>
<!-- Generated by tools/build_privacy_page.py from the app's strings. Do not edit by hand. -->
<html lang="{lang}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{html.escape(get("privacy_title"))} – {html.escape(get("app_name"))}</title>
<style>
  :root {{ color-scheme: light dark; --fg: #1c1b1a; --bg: #faf8f4; --muted: #5f5b55; --link: #9b1c2e; }}
  @media (prefers-color-scheme: dark) {{ :root {{ --fg: #ece8e1; --bg: #1a1918; --muted: #b3ada4; --link: #f08a96; }} }}
  body {{ margin: 0; background: var(--bg); color: var(--fg); font: 17px/1.6 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif; }}
  main {{ max-width: 42rem; margin: 0 auto; padding: 2rem 1rem 4rem; }}
  h1 {{ font-size: 1.8rem; line-height: 1.25; margin: 0 0 .25rem; }}
  h2 {{ font-size: 1.2rem; margin: 2rem 0 .5rem; }}
  .meta {{ color: var(--muted); font-size: .9rem; }}
  a {{ color: var(--link); }}
</style>
</head>
<body>
<main>
<p class="meta">{other}</p>
<h1>{html.escape(get("privacy_title"))}</h1>
<p class="meta">{html.escape(fill(get("privacy_updated"), date_text))}</p>
{chr(10).join(body)}
</main>
</body>
</html>
"""


def main() -> None:
    check = "--check" in sys.argv[1:]
    targets = {OUT / "index.html": page("en"), OUT / "es" / "index.html": page("es")}
    stale = [p for p, text in targets.items() if not p.exists() or p.read_text() != text]
    if check:
        if stale:
            sys.exit("Out of date (run tools/build_privacy_page.py): " + ", ".join(str(p.relative_to(ROOT)) for p in stale))
        print("Privacy pages are up to date.")
        return
    for path, text in targets.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"Wrote {path.relative_to(ROOT)}")
    if "@" not in support_email():
        print("Warning: supportEmail in app/build.gradle.kts is still a placeholder; the Contact line shows it as is.")


if __name__ == "__main__":
    main()
